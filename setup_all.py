    # ---- 灌数据 / 清空 ----
    if not args.verify:
        if not args.clean:
            ph = ','.join(['?'] * len(COLUMNS))
            col_list = ','.join(COLUMNS)
            for r in RECORDS:
                vals = [r.get(k, None) for k in COLUMNS]
                c.execute(
                    f'INSERT INTO won_projects(no,{col_list}) VALUES (?,{ph})',
                    [r['no']] + vals
                )
            conn.commit()
            print(f"🌱 已灌入 {len(RECORDS)} 条完整数据")
        else:
            print("🧹 仅清空模式，未灌数据")

    # ---- 验证 ----
    rows = c.execute(
        "SELECT id, contract_no, customer, total_ei_rmb, cust_paid_rmb, gs_comm_rmb, agi_payable_rmb "
        "FROM won_projects ORDER BY id"
    ).fetchall()

    print(f"\n📋 数据库内共 {len(rows)} 条记录：")
    for r in rows:
        print(
            f"  #{r['id']}  {r['contract_no']:<16}  "
            f"客户={r['customer']:<10}  "
            f"EI(RMB)={r['total_ei_rmb']:>10,}  "
            f"已付(RMB)={r['cust_paid_rmb']:>8,}  "
            f"佣金(RMB)={r['gs_comm_rmb']:>8,}  "
            f"应付AGI(RMB)={r['agi_payable_rmb']:>10,}"
        )

    # ---- JSON 完整性校验 ----
    print("\n🔍 JSON 字段完整性校验：")
    json_ok = True
    for r in c.execute("SELECT id, contract_no, cust_view_detail, gs_view_detail FROM won_projects").fetchall():
        for field_name, raw in [("cust_view_detail", r["cust_view_detail"]),
                                 ("gs_view_detail", r["gs_view_detail"])]:
            if raw:
                try:
                    json.loads(raw)
                except Exception as e:
                    json_ok = False
                    print(f"  ❌ #{r['id']} {r['contract_no']} {field_name}: JSON 解析失败 - {e}")

    if json_ok:
        print("  ✅ 所有 JSON 字段均解析正常")

    # ---- 汇总统计 ----
    sums = c.execute(
        "SELECT COALESCE(SUM(total_ei_rmb),0) AS ei, "
        "COALESCE(SUM(cust_paid_rmb),0) AS paid, "
        "COALESCE(SUM(gs_comm_rmb),0) AS comm, "
        "COALESCE(SUM(agi_payable_rmb),0) AS agi "
        "FROM won_projects"
    ).fetchone()

    print(
        f"\n📊 汇总：EI(RMB)={sums['ei']:,}  |  "
        f"已付(RMB)={sums['paid']:,}  |  "
        f"佣金(RMB)={sums['comm']:,}  |  "
        f"应付AGI(RMB)={sums['agi']:,}"
    )

    conn.close()
    print("\n✅ 初始化完成")


